CREATE SEQUENCE SEQ_PROTOCOLO START WITH 1 INCREMENT BY 1;

CREATE TABLE ORGAOS (
    ID    NUMBER(10)     NOT NULL,
    NOME  VARCHAR2(120)  NOT NULL,
    CONSTRAINT PK_ORGAOS PRIMARY KEY (ID),
    CONSTRAINT UQ_ORGAOS_NOME UNIQUE (NOME)
);

CREATE TABLE CATEGORIAS (
    ID                 NUMBER(10)     NOT NULL,
    NOME               VARCHAR2(80)   NOT NULL,
    ORGAO_ID           NUMBER(10)     NOT NULL,
    PRAZO_DIAS         NUMBER(3)      NOT NULL,
    PRIORIDADE_PADRAO  VARCHAR2(10)   DEFAULT 'BAIXA' NOT NULL,
    CONSTRAINT PK_CATEGORIAS PRIMARY KEY (ID),
    CONSTRAINT UQ_CATEGORIAS_NOME UNIQUE (NOME),
    CONSTRAINT FK_CATEGORIAS_ORGAO FOREIGN KEY (ORGAO_ID) REFERENCES ORGAOS (ID),
    CONSTRAINT CK_CATEGORIAS_PRIO CHECK (PRIORIDADE_PADRAO IN ('BAIXA','MEDIA','ALTA')),
    CONSTRAINT CK_CATEGORIAS_PRAZO CHECK (PRAZO_DIAS > 0)
);

CREATE TABLE CIDADAOS (
    ID         NUMBER(10)     NOT NULL,
    NOME       VARCHAR2(120)  NOT NULL,
    BAIRRO     VARCHAR2(80),
    CRIADO_EM  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CIDADAOS PRIMARY KEY (ID)
);

CREATE TABLE OCORRENCIAS (
    ID            NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    PROTOCOLO     VARCHAR2(20)    NOT NULL,
    CIDADAO_ID    NUMBER(10)      NOT NULL,
    CATEGORIA_ID  NUMBER(10)      NOT NULL,
    DESCRICAO     VARCHAR2(500)   NOT NULL,
    LATITUDE      NUMBER(9,6)     NOT NULL,
    LONGITUDE     NUMBER(9,6)     NOT NULL,
    ENDERECO      VARCHAR2(250),
    STATUS        VARCHAR2(15)    DEFAULT 'ABERTA' NOT NULL,
    PRIORIDADE    VARCHAR2(10)    DEFAULT 'BAIXA'  NOT NULL,
    QTD_APOIOS    NUMBER(6)       DEFAULT 0 NOT NULL,
    CRIADO_EM     TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    RESOLVIDO_EM  TIMESTAMP,
    CONSTRAINT PK_OCORRENCIAS PRIMARY KEY (ID),
    CONSTRAINT UQ_OCORRENCIAS_PROTOCOLO UNIQUE (PROTOCOLO),
    CONSTRAINT FK_OCORR_CIDADAO   FOREIGN KEY (CIDADAO_ID)   REFERENCES CIDADAOS (ID),
    CONSTRAINT FK_OCORR_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS (ID),
    CONSTRAINT CK_OCORR_STATUS CHECK (STATUS IN ('ABERTA','EM_ANALISE','EM_ANDAMENTO','RESOLVIDA')),
    CONSTRAINT CK_OCORR_PRIO   CHECK (PRIORIDADE IN ('BAIXA','MEDIA','ALTA')),
    CONSTRAINT CK_OCORR_LAT    CHECK (LATITUDE  BETWEEN -90  AND 90),
    CONSTRAINT CK_OCORR_LON    CHECK (LONGITUDE BETWEEN -180 AND 180)
);

CREATE INDEX IX_OCORR_STATUS    ON OCORRENCIAS (STATUS);
CREATE INDEX IX_OCORR_CATEGORIA ON OCORRENCIAS (CATEGORIA_ID);

CREATE TABLE HISTORICO_OCORRENCIA (
    ID             NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    OCORRENCIA_ID  NUMBER(19)      NOT NULL,
    STATUS_ANTIGO  VARCHAR2(15),
    STATUS_NOVO    VARCHAR2(15)    NOT NULL,
    OBSERVACAO     VARCHAR2(300),
    ALTERADO_EM    TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HISTORICO PRIMARY KEY (ID),
    CONSTRAINT FK_HIST_OCORRENCIA FOREIGN KEY (OCORRENCIA_ID) REFERENCES OCORRENCIAS (ID)
);

CREATE INDEX IX_HIST_OCORRENCIA ON HISTORICO_OCORRENCIA (OCORRENCIA_ID);

CREATE TABLE APOIOS (
    ID             NUMBER(19)  GENERATED BY DEFAULT AS IDENTITY,
    OCORRENCIA_ID  NUMBER(19)  NOT NULL,
    CIDADAO_ID     NUMBER(10)  NOT NULL,
    CRIADO_EM      TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APOIOS PRIMARY KEY (ID),
    CONSTRAINT UQ_APOIOS UNIQUE (OCORRENCIA_ID, CIDADAO_ID),
    CONSTRAINT FK_APOIOS_OCORR   FOREIGN KEY (OCORRENCIA_ID) REFERENCES OCORRENCIAS (ID),
    CONSTRAINT FK_APOIOS_CIDADAO FOREIGN KEY (CIDADAO_ID)    REFERENCES CIDADAOS (ID)
);
